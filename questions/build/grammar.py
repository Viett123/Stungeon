# type: "multiple_choice" | "multi_select" | "typed"
# For typed questions, "accept" lists other answers that also count as correct.

def mc(e, topic, diff, q, choices, answer, expl):
    return dict(einheit=e, topic=topic, difficulty=diff, type="multiple_choice",
                question=q, choices=choices, answer=answer, explanation=expl)

def ms(e, topic, diff, q, choices, answers, expl):
    return dict(einheit=e, topic=topic, difficulty=diff, type="multi_select",
                question=q, choices=choices, answer=answers, explanation=expl)

def ty(e, topic, diff, q, answer, expl, accept=()):
    return dict(einheit=e, topic=topic, difficulty=diff, type="typed",
                question=q, answer=answer, accept=list(accept), explanation=expl)

